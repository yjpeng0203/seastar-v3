def poisson_interval(n):
    if n<len(_SMALL_POISSON):return _SMALL_POISSON[n]
    # Wilson-Hilferty approximation to the same central gamma-quantile limits.
    lower=n*(1-1/(9*n)-1/(3*math.sqrt(n)))**3
    m=n+1;upper=m*(1-1/(9*m)+1/(3*math.sqrt(m)))**3
    return max(0.,lower),upper


def wilson_interval(p,n):
    if n<=0:return None,None
    center=(p+.5/n)/(1+1/n)
    half=math.sqrt(max(0.,p*(1-p)/n+.25/(n*n)))/(1+1/n)
    return max(0.,center-half),min(1.,center+half)
